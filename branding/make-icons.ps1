# Generates every app icon from branding\barcode-logo.svg (colour) and branding\barcode-logo-white.svg (silhouette).
# The SVGs are the only source: edit them, then run this script. Needs Windows (WPF draws the PNGs).
#   powershell -NoProfile -ExecutionPolicy Bypass -File branding\make-icons.ps1
Add-Type -AssemblyName PresentationCore, WindowsBase
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot
$res = Join-Path $root 'app\src\main\res'
$ns = @{ s = 'http://www.w3.org/2000/svg' }

function Read-Logo([string]$path) {
    [xml]$doc = Get-Content $path -Raw -Encoding UTF8
    $vb = $doc.svg.viewBox -split '[\s,]+' | ForEach-Object { [double]$_ }
    $paths = foreach ($p in (Select-Xml -Xml $doc -XPath '//s:path' -Namespace $ns).Node) {
        $fill = $p.GetAttribute('fill'); if (-not $fill) { $fill = $p.ParentNode.GetAttribute('fill') }
        [pscustomobject]@{ D = $p.d; Fill = $fill; EvenOdd = $p.GetAttribute('fill-rule') -eq 'evenodd' }
    }
    [pscustomobject]@{ Doc = $doc; ViewBox = $vb; Paths = $paths }
}

function Get-Brush($logo, [string]$fill) {
    if ($fill -match '^url\(#(.+)\)$') {
        $g = (Select-Xml -Xml $logo.Doc -XPath "//s:linearGradient[@id='$($Matches[1])']" -Namespace $ns).Node
        $b = New-Object Windows.Media.LinearGradientBrush
        $b.MappingMode = 'Absolute'
        $b.StartPoint = [Windows.Point]::new([double]$g.x1, [double]$g.y1)
        $b.EndPoint = [Windows.Point]::new([double]$g.x2, [double]$g.y2)
        foreach ($st in $g.stop) {
            $b.GradientStops.Add((New-Object Windows.Media.GradientStop([Windows.Media.ColorConverter]::ConvertFromString($st.'stop-color'), [double]$st.offset)))
        }
    } else {
        $b = New-Object Windows.Media.SolidColorBrush([Windows.Media.ColorConverter]::ConvertFromString($fill))
    }
    $b.Freeze(); $b
}

# Draws the logo centred on a $size square, its longer side taking $frac of it, over an optional background.
function Write-Png($logo, [string]$out, [int]$size, [double]$frac, [string]$bg) {
    $vb = $logo.ViewBox
    $dv = New-Object Windows.Media.DrawingVisual
    $dc = $dv.RenderOpen()
    if ($bg) {
        $bb = New-Object Windows.Media.SolidColorBrush([Windows.Media.ColorConverter]::ConvertFromString($bg))
        $dc.DrawRectangle($bb, $null, (New-Object Windows.Rect(0, 0, $size, $size)))
    }
    $k = $size * $frac / [Math]::Max($vb[2], $vb[3])
    $ox = ($size - $vb[2] * $k) / 2 - $vb[0] * $k; $oy = ($size - $vb[3] * $k) / 2 - $vb[1] * $k
    $dc.PushTransform((New-Object Windows.Media.MatrixTransform($k, 0, 0, $k, $ox, $oy)))
    foreach ($p in $logo.Paths) {
        $rule = if ($p.EvenOdd) { 'F0 ' } else { 'F1 ' }
        $dc.DrawGeometry((Get-Brush $logo $p.Fill), $null, [Windows.Media.Geometry]::Parse($rule + $p.D))
    }
    $dc.Pop(); $dc.Close()
    $bmp = New-Object Windows.Media.Imaging.RenderTargetBitmap($size, $size, 96, 96, [Windows.Media.PixelFormats]::Pbgra32)
    $bmp.Render($dv)
    $enc = New-Object Windows.Media.Imaging.PngBitmapEncoder
    $enc.Frames.Add([Windows.Media.Imaging.BitmapFrame]::Create($bmp))
    New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
    $fs = [IO.File]::Create($out); $enc.Save($fs); $fs.Close()
}

# Writes an Android vector drawable from the white silhouette, the logo scaled by $scale and moved by $tx/$ty.
function Write-Vector($logo, [string]$out, [string]$dp, [double]$viewport, [double]$scale, [double]$tx, [double]$ty) {
    $inv = [Globalization.CultureInfo]::InvariantCulture
    $paths = foreach ($p in $logo.Paths) {
        $type = if ($p.EvenOdd) { "`n            android:fillType=`"evenOdd`"" } else { '' }
        "        <path$type`n            android:fillColor=`"#FFFFFFFF`"`n            android:pathData=`"$($p.D)`" />"
    }
    $xml = @"
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by branding/make-icons.ps1 from branding/barcode-logo-white.svg. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${dp}dp"
    android:height="${dp}dp"
    android:viewportWidth="$($viewport.ToString($inv))"
    android:viewportHeight="$($viewport.ToString($inv))">
    <group
        android:scaleX="$($scale.ToString('0.####', $inv))"
        android:scaleY="$($scale.ToString('0.####', $inv))"
        android:translateX="$($tx.ToString('0.###', $inv))"
        android:translateY="$($ty.ToString('0.###', $inv))">
$($paths -join "`n")
    </group>
</vector>
"@
    New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
    [IO.File]::WriteAllText($out, $xml.Replace("`r`n", "`n"), (New-Object Text.UTF8Encoding($false)))
}

$colour = Read-Logo (Join-Path $PSScriptRoot 'barcode-logo.svg')
$white = Read-Logo (Join-Path $PSScriptRoot 'barcode-logo-white.svg')

# Launcher icons per density. The adaptive foreground keeps the logo inside the 66dp safe zone of its 108dp canvas.
$densities = [ordered]@{ mdpi = 1; hdpi = 1.5; xhdpi = 2; xxhdpi = 3; xxxhdpi = 4 }
foreach ($d in $densities.Keys) {
    $f = $densities[$d]
    Write-Png $colour (Join-Path $res "mipmap-$d\ic_launcher.png") ([int](48 * $f)) 0.92 $null
    Write-Png $colour (Join-Path $res "mipmap-$d\ic_launcher_foreground.png") ([int](108 * $f)) 0.55 $null
}

# Store listings: Google Play (white square, the store rounds it) and the F-Droid/fastlane metadata icon.
Write-Png $colour (Join-Path $root 'app\src\main\ic_launcher-playstore.png') 512 0.72 '#FFFFFF'
Write-Png $colour (Join-Path $root 'metadata\en-US\images\icon.png') 512 0.86 $null

# Notification icon (24dp, logo fills the viewport) and the themed monochrome icon (logo about 48dp on 108dp).
$vb = $white.ViewBox
Write-Vector $white (Join-Path $res 'drawable\ic_stat_logo.xml') 24 $vb[2] 1 (-$vb[0]) (-$vb[1])
$s = 48 / $vb[2]
$c = $vb[0] + $vb[2] / 2
Write-Vector $white (Join-Path $res 'drawable\ic_launcher_mono.xml') 108 108 $s (54 - $c * $s) (54 - $c * $s)

# Windows receiver (windows\src\BarcodeReceiver\Assets): app.ico with PNG frames 16 to 256, and the 128 px logo of the
# window header and About.
$win = Join-Path $root 'windows\src\BarcodeReceiver\Assets'
$tmp = Join-Path ([IO.Path]::GetTempPath()) 'barcode-ico'
$sizes = 16, 20, 24, 32, 40, 48, 64, 128, 256
$frames = foreach ($sz in $sizes) {
    $png = Join-Path $tmp "$sz.png"
    Write-Png $colour $png $sz 0.94 $null
    , [IO.File]::ReadAllBytes($png)
}
$ico = New-Object IO.MemoryStream
$w = New-Object IO.BinaryWriter($ico)
$w.Write([uint16]0); $w.Write([uint16]1); $w.Write([uint16]$sizes.Count)   # ICONDIR: reserved, type icon, count
$offset = 6 + 16 * $sizes.Count
for ($i = 0; $i -lt $sizes.Count; $i++) {
    $sz = $sizes[$i]; $len = $frames[$i].Length
    $w.Write([byte]($sz % 256)); $w.Write([byte]($sz % 256))                 # 256 is written as 0
    $w.Write([byte]0); $w.Write([byte]0); $w.Write([uint16]1); $w.Write([uint16]32)
    $w.Write([uint32]$len); $w.Write([uint32]$offset)
    $offset += $len
}
foreach ($f in $frames) { $w.Write($f) }
$w.Flush()
New-Item -ItemType Directory -Force $win | Out-Null
[IO.File]::WriteAllBytes((Join-Path $win 'app.ico'), $ico.ToArray())
Write-Png $colour (Join-Path $win 'logo.png') 128 0.94 $null
Remove-Item $tmp -Recurse -Force

'Icons generated from branding\barcode-logo.svg'
